import type { CategoryKey, ScorePoint, TrendCard, TrendStatus } from '../lib/types'

function daysAgo(n: number): string {
  const d = new Date()
  d.setDate(d.getDate() - n)
  return d.toISOString().slice(0, 10)
}

function history(points: number[]): ScorePoint[] {
  const n = points.length
  return points.map((score, i) => ({ date: daysAgo(n - 1 - i), score }))
}

